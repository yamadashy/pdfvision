// A cash-flow statement in the 10-K style: a label column and two
// right-aligned year columns, `$` drawn as its own glyph at the left of the
// column on the first and total rows, negatives in parentheses, and `—`
// standing in for zero. One row is `—` in both years.

const YEARS = ['2024', '2023'];
const TITLE = 'CONSOLIDATED STATEMENTS OF CASH FLOWS';
const UNITS = '(In millions)';
// kind: 'section' rows carry no values; 'first' and 'total' rows carry `$`.
const ROWS = [
  { label: 'Operating activities:', kind: 'section' },
  { label: 'Net income', values: ['93,736', '96,995'], kind: 'first' },
  { label: 'Adjustments to reconcile net income to cash generated by operating activities:', kind: 'section' },
  { label: 'Depreciation and amortization', values: ['11,445', '11,519'] },
  { label: 'Share-based compensation expense', values: ['11,688', '10,833'] },
  { label: 'Deferred income tax benefit', values: ['(4,738)', '—'] },
  { label: 'Restructuring charges', values: ['—', '—'] },
  { label: 'Other', values: ['(2,266)', '(2,227)'] },
  { label: 'Changes in operating assets and liabilities:', kind: 'section' },
  { label: 'Accounts receivable, net', values: ['(3,788)', '(1,688)'] },
  { label: 'Vendor non-trade receivables', values: ['—', '1,271'] },
  { label: 'Inventories', values: ['(1,046)', '(1,618)'] },
  { label: 'Cash generated by operating activities', values: ['118,254', '110,543'], kind: 'total' },
];

export const meta = {
  title: 'Statement with dash placeholders',
  stresses:
    '`—` as an empty value, a row that is `—` in every column, `$` drawn as a separate glyph, parenthesised negatives',
  status: 'known-gap',
  families: ['tables'],
};

const valued = ROWS.filter((row) => row.values);
const dashOnly = valued.filter((row) => row.values.every((value) => value === '—'));
const withCurrency = (row, value) => (row.kind === 'first' || row.kind === 'total' ? `$ ${value}` : value);

export const truth = `
${TITLE} ${UNITS}: ${valued.length} rows with values under the years ${YEARS.join(' and ')}, plus
${ROWS.length - valued.length} section label rows with no values. \`—\` means zero/none and holds its
column; it must not shift a value into the other year. \`(4,738)\` is a negative number.

| Line item | ${YEARS.join(' | ')} |
| --- | ---: | ---: |
${ROWS.map((row) => `| ${row.label} | ${row.values ? row.values.map((value) => withCurrency(row, value)).join(' | ') : ' | '} |`).join('\n')}

The \`$\` belongs to the value on its right. The section label rows may be
emitted as label-only rows or left out of the table, as long as their text
appears in reading order.

${dashOnly.map((row) => `\`${row.label}\``).join(', ')} has \`—\` in both columns. Under the current table
rules (\`src/core/layout/tableCandidateRows.ts\`, \`hasTableValueCells\`) a row only counts
as table evidence when at least two cells are values *and* one of them contains a
digit, so this row cannot start or extend a table by itself. A reading that keeps it
as a row of the table is better; one that drops it from the table must still carry
the text in the page body.

**Known gap (no issue yet):** pdfvision returns no layout table and no
\`tabular_numeric_layout\` warning for this page. The values come out as one run per
column (\`93,736\`, \`11,445\`, … then \`2024\`), so none can be tied to its row. The
\`${dashOnly[0].label}\` row splits the table into an upper and a lower fragment and
neither is kept: with that row given numbers the whole 15-row table is found correctly;
with the row kept but \`Vendor non-trade receivables\` given a number instead of \`—\`,
only the six rows below it survive.
`;

const LEFT = 72;
const LABEL_WIDTH = 300;
const COLUMN_RIGHT = [470, 540];
const COLUMN_LEFT = [410, 480];

export function draw(doc, h) {
  let y = 80;
  h.text(TITLE, 306, y, { font: 'Helvetica-Bold', size: 11, align: 'center' });
  y += 16;
  h.text(UNITS, 306, y, { size: 9, align: 'center' });
  y += 24;

  YEARS.forEach((year, i) => {
    h.text(year, COLUMN_RIGHT[i], y, { font: 'Helvetica-Bold', align: 'right' });
  });
  y += 14;
  h.rule(COLUMN_LEFT[0], y, COLUMN_RIGHT[1]);
  y += 6;

  for (const row of ROWS) {
    const indent = row.kind === 'section' || row.kind === 'first' || row.kind === 'total' ? 0 : 12;
    const font = row.kind === 'total' ? 'Helvetica-Bold' : 'Helvetica';
    if (row.kind === 'total') h.rule(COLUMN_LEFT[0], y - 3, COLUMN_RIGHT[1]);
    h.paragraph(row.label, LEFT + indent, y, LABEL_WIDTH - indent, { font, size: 10, lineGap: 1 });
    const labelBottom = doc.y;
    if (row.values) {
      // A wrapped label puts its values on its last line, as statements do.
      const valueY = labelBottom - (doc.currentLineHeight(true) + 1);
      row.values.forEach((value, i) => {
        if (row.kind === 'first' || row.kind === 'total') h.text('$', COLUMN_LEFT[i], valueY, { font });
        h.text(value, COLUMN_RIGHT[i], valueY, { font, align: 'right' });
      });
    }
    y = labelBottom + 4;
    if (row.kind === 'total') {
      h.rule(COLUMN_LEFT[0], y - 1, COLUMN_RIGHT[1]);
      h.rule(COLUMN_LEFT[0], y + 1, COLUMN_RIGHT[1]);
    }
  }
}
