// Case metadata vocabulary and the generated COVERAGE.md.
//
// Every case names the pattern families it exercises (`meta.families`). The
// families come from a survey of real PDFs; COVERAGE.md shows, per family,
// which cases exist, which are showcases (hard, yet read correctly or
// recovered through a warning that names the next step), and which are gaps.

export const FAMILIES = {
  encoding:
    'glyph-to-text mapping: symbol fonts, missing or garbage ToUnicode, overdrawn bold, ligatures, letter-spacing',
  math: 'sub/superscripts, display equations, matrices',
  'reading-order': 'columns, sidebars, floats, margin text',
  tables: 'tables',
  'vertical-rotated': 'vertical writing, rotated pages and labels',
  'raster-text': 'text that exists only in images, scans, OCR layers',
  'vector-meaning': 'charts, diagrams, icons and fills that carry meaning',
  'hidden-overlap': 'invisible, duplicated, covered, watermark and overlay text',
  interactive: 'forms, annotations, links, outline, attachments',
  structure: 'running heads, TOC, footnotes, lists, code blocks',
  scripts: 'non-Latin scripts and bidi',
  'page-geometry': 'unusual page sizes, n-up, mixed orientation',
};

const STATUSES = ['ok', 'known-gap'];

/** Throw a message naming the case and the field for any malformed `meta`. */
export function validateMeta(name, meta, fail) {
  const where = `cases/${name}/build.mjs: meta`;
  for (const key of ['title', 'stresses']) {
    if (typeof meta[key] !== 'string' || meta[key].trim() === '') fail(`${where}.${key} must be a non-empty string`);
  }
  if (!STATUSES.includes(meta.status)) fail(`${where}.status must be one of ${STATUSES.join(', ')}`);
  if (!Array.isArray(meta.families) || meta.families.length === 0) {
    fail(`${where}.families must be a non-empty array of: ${Object.keys(FAMILIES).join(', ')}`);
  }
  const unknown = meta.families.filter((family) => !Object.hasOwn(FAMILIES, family));
  if (unknown.length > 0) {
    fail(`${where}.families has unknown ${unknown.join(', ')} (allowed: ${Object.keys(FAMILIES).join(', ')})`);
  }
  if (new Set(meta.families).size !== meta.families.length) fail(`${where}.families lists a family twice`);
  if (meta.showcase !== undefined && meta.showcase !== true) fail(`${where}.showcase must be true or absent`);
  if (meta.showcase) {
    if (meta.status !== 'ok') fail(`${where}.showcase is only valid with status 'ok'`);
    if (typeof meta.hard !== 'string' || meta.hard.trim() === '') {
      fail(`${where}.showcase needs meta.hard: one sentence on why this is hard for PDF extraction`);
    }
  } else if (meta.hard !== undefined) {
    fail(`${where}.hard is only used together with showcase: true`);
  }
  if (meta.compress !== undefined && typeof meta.compress !== 'boolean') fail(`${where}.compress must be a boolean`);
}

export function statusLabel(meta) {
  if (meta.status !== 'known-gap') return meta.showcase ? 'ok, showcase' : 'ok';
  return meta.issue ? `known-gap #${meta.issue}` : 'known-gap';
}

export function renderCoverage(cases) {
  const families = Object.keys(FAMILIES);
  const inFamily = (family) => cases.filter(({ meta }) => meta.families.includes(family));
  const showcases = cases.filter(({ meta }) => meta.showcase);
  const gaps = cases.filter(({ meta }) => meta.status === 'known-gap');
  const noCase = families.filter((family) => inFamily(family).length === 0);
  const noShowcase = families.filter((family) => !inFamily(family).some(({ meta }) => meta.showcase));
  const list = (names) => (names.length > 0 ? names.map((n) => `\`${n}\``).join(', ') : 'none');

  const matrix = families.map((family) => {
    const members = inFamily(family);
    const cells = members.map(({ name, meta }) => `\`${name}\` (${statusLabel(meta)})`).join(', ');
    let flag = '';
    if (members.length === 0) flag = '**no case**';
    else if (!members.some(({ meta }) => meta.showcase)) flag = 'no showcase';
    return `| \`${family}\` | ${FAMILIES[family]} | ${cells || '—'} | ${flag} |`;
  });

  return `# Playground coverage

Generated by \`node --run playground\` from each case's \`meta\`; do not edit by hand
(\`node --run playground -- --check\` fails when this file is stale). See \`README.md\` for what
the families, showcases and statuses mean.

${cases.length} cases · ${cases.length - gaps.length} ok (${showcases.length} showcase) · ${gaps.length} known gap${gaps.length === 1 ? '' : 's'}

## Families

| Family | Covers | Cases | Flag |
| --- | --- | --- | --- |
${matrix.join('\n')}

- Families with no case: ${list(noCase)}
- Families with no showcase: ${list(noShowcase)}

## Showcases

Hard for PDF extraction, yet read correctly or recovered through a warning that names the next step.

${showcases.map(({ name, meta }) => `- \`${name}\` — ${meta.title} (${meta.families.join(', ')}). ${meta.hard.trim()}`).join('\n') || '- none'}

## Known gaps

${gaps.map(({ name, meta }) => `- \`${name}\` — ${meta.title} (${meta.families.join(', ')}) — ${meta.issue ? `#${meta.issue}` : 'no issue yet'}`).join('\n') || '- none'}
`;
}
