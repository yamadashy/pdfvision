#!/usr/bin/env node
// Generate the built-in `pdfvision docs` topics from docs/cli-topics/*.md,
// and the per-code warning entries from docs/cli-topics/warnings/*.md.
//
// The topics ship inside the bundle rather than as files because the npm
// package contains only `dist/`, README, and LICENSE: an installed pdfvision
// has no Markdown to read. Embedding also ties the documentation to the
// version that is actually installed, which is the whole point of answering
// `pdfvision docs` from the binary instead of the web.
//
// Two outputs, because they have different lifetimes:
//   - topicIndex.generated.ts   names + descriptions; small enough for the
//                               main chunk, which `--help` needs.
//   - topicBodies.generated.ts  the prose; imported dynamically so a normal
//                               extraction never parses it.
//
// Warning entries are one file per code so an agent holding a code can read
// just that code (`pdfvision docs warnings <code>`), and so an edit to one
// code never touches another's lines. Each entry's frontmatter `summary` and
// `availability` also build the code index that replaces the
// `<!-- warning-index -->` marker in the `warnings` topic, so the one-line
// gloss and the entry cannot drift apart.
//
// The outputs are committed and CI re-runs this script and diffs, the same
// arrangement `scripts/sync-readme-usage.mjs` uses for the README.
//
// Kept build-free so it runs on every Node in the support matrix without
// relying on TypeScript type-stripping.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const topicsDir = resolve(repoRoot, 'docs/cli-topics');
const warningsDir = join(topicsDir, 'warnings');
const outDir = resolve(repoRoot, 'src/cli/docs');

const NAME_PATTERN = /^[a-z][a-z0-9-]*$/;
const CODE_PATTERN = /^[a-z][a-z0-9_]*$/;
const WARNING_INDEX_MARKER = '<!-- warning-index -->';
const GENERATED_HEADER = `// Generated by scripts/build-cli-topics.mjs from docs/cli-topics/*.md.
// Do not edit by hand; run \`node scripts/build-cli-topics.mjs\`.
`;

function fail(message) {
  console.error(`build-cli-topics: ${message}`);
  process.exit(1);
}

/**
 * Deliberately not a YAML parser: the frontmatter is a few single-line string
 * fields, and accepting more would let a topic carry structure the CLI has
 * no way to render.
 */
function parseFrontmatter(dir, file) {
  // Normalize line endings first: a Windows worktree with core.autocrlf
  // checks these out as CRLF, and `prepare` runs this on install.
  const raw = readFileSync(join(dir, file), 'utf8').replace(/\r\n?/g, '\n');
  if (!raw.startsWith('---\n')) fail(`${file} does not start with YAML frontmatter`);
  const end = raw.indexOf('\n---\n', 3);
  if (end === -1) fail(`${file} has an unterminated frontmatter block`);

  const fields = {};
  for (const line of raw.slice(4, end + 1).split('\n')) {
    if (line.trim() === '') continue;
    const match = /^([a-z]+):\s*(.*)$/.exec(line);
    if (!match) fail(`${file} has a frontmatter line this script cannot read: ${line}`);
    const [, key, value] = match;
    fields[key] = value.replace(/^["'](.*)["']$/, '$1').trim();
  }
  return { fields, body: raw.slice(end + 5).trim() };
}

function parseTopic(file) {
  const { fields, body } = parseFrontmatter(topicsDir, file);
  const expectedName = file.replace(/\.md$/, '');
  if (fields.name !== expectedName) {
    fail(`${file} declares name "${fields.name ?? ''}"; it must match the filename ("${expectedName}")`);
  }
  if (!NAME_PATTERN.test(expectedName)) fail(`${file} is not a usable topic name (lowercase, digits, dashes)`);
  if (!fields.description) fail(`${file} has no description; the index is how an agent picks a topic`);
  if (!body) fail(`${file} has no body`);
  return { name: expectedName, description: fields.description, body };
}

/**
 * An entry may have an empty body: some codes are fully said by their
 * summary. The summary and availability are required because the index
 * line is built from them.
 */
function parseWarningEntry(file) {
  const { fields, body } = parseFrontmatter(warningsDir, file);
  const expectedCode = file.replace(/\.md$/, '');
  if (fields.code !== expectedCode) {
    fail(`warnings/${file} declares code "${fields.code ?? ''}"; it must match the filename ("${expectedCode}")`);
  }
  if (!CODE_PATTERN.test(expectedCode)) fail(`warnings/${file} is not a warning code (lowercase, digits, underscores)`);
  for (const key of ['availability', 'summary']) {
    if (!fields[key]) fail(`warnings/${file} has no ${key}; the code index is built from it`);
  }
  const extra = Object.keys(fields).filter((key) => !['code', 'availability', 'summary'].includes(key));
  if (extra.length > 0) fail(`warnings/${file} has frontmatter fields this script does not render: ${extra.join(', ')}`);
  return { code: expectedCode, availability: fields.availability, summary: fields.summary, body };
}

function renderWarningEntry(entry) {
  const parts = [`# Warning \`${entry.code}\``, `Availability: ${entry.availability}.`, entry.summary];
  if (entry.body) parts.push(entry.body);
  parts.push('Every code, with the shape and severity: `pdfvision docs warnings`.');
  return parts.join('\n\n');
}

function renderWarningIndex(entries) {
  return entries.map((entry) => `- \`${entry.code}\` [${entry.availability}] — ${entry.summary}`).join('\n');
}

const files = readdirSync(topicsDir)
  .filter((file) => file.endsWith('.md'))
  .sort();
if (files.length === 0) fail(`no topics found in ${topicsDir}`);

const topics = files.map(parseTopic);

const warningEntries = readdirSync(warningsDir)
  .filter((file) => file.endsWith('.md'))
  .sort()
  .map(parseWarningEntry);
if (warningEntries.length === 0) fail(`no warning entries found in ${warningsDir}`);

const warningsTopic = topics.find((topic) => topic.name === 'warnings');
if (!warningsTopic) fail('the warnings topic is missing; the warning entries have nowhere to be indexed');
if (warningsTopic.body.split(WARNING_INDEX_MARKER).length !== 2) {
  fail(`warnings.md must contain the ${WARNING_INDEX_MARKER} marker exactly once`);
}
warningsTopic.body = warningsTopic.body.replace(WARNING_INDEX_MARKER, renderWarningIndex(warningEntries));

const indexEntries = topics
  .map((topic) => `  { name: ${JSON.stringify(topic.name)}, description: ${JSON.stringify(topic.description)} },`)
  .join('\n');
const indexSource = `${GENERATED_HEADER}
export interface CliTopicSummary {
  name: string;
  description: string;
}

export const CLI_TOPIC_INDEX: readonly CliTopicSummary[] = [
${indexEntries}
];

/** Codes with an entry under \`pdfvision docs warnings <code>\`. */
export const CLI_WARNING_CODES: readonly string[] = [
${warningEntries.map((entry) => `  ${JSON.stringify(entry.code)},`).join('\n')}
];
`;

const bodyEntries = topics.map((topic) => `  ${JSON.stringify(topic.name)}: ${JSON.stringify(topic.body)},`).join('\n');
const bodiesSource = `${GENERATED_HEADER}
export const CLI_TOPIC_BODIES: Record<string, string> = {
${bodyEntries}
};

export const CLI_WARNING_ENTRIES: Record<string, string> = {
${warningEntries.map((entry) => `  ${JSON.stringify(entry.code)}: ${JSON.stringify(renderWarningEntry(entry))},`).join('\n')}
};
`;

let changed = false;
for (const [file, source] of [
  ['topicIndex.generated.ts', indexSource],
  ['topicBodies.generated.ts', bodiesSource],
]) {
  const path = join(outDir, file);
  let previous = '';
  try {
    previous = readFileSync(path, 'utf8');
  } catch {
    // first run
  }
  if (previous === source) continue;
  writeFileSync(path, source);
  changed = true;
}

console.log(
  changed
    ? `Generated ${topics.length} CLI topics and ${warningEntries.length} warning entries from docs/cli-topics/.`
    : `CLI topics already up to date (${topics.length} topics, ${warningEntries.length} warning entries).`,
);
