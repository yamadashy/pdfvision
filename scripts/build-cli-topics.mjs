#!/usr/bin/env node
// Generate the built-in `pdfvision docs` topics from docs/cli-topics/*.md.
//
// The topics ship inside the bundle rather than as files because the npm
// package contains only `dist/`, README, and LICENSE: an installed pdfvision
// has no Markdown to read. Embedding also ties the documentation to the
// version that is actually installed, which is the whole point of answering
// `pdfvision docs` from the binary instead of the web.
//
// Two outputs, because they have different lifetimes:
//   - topicIndex.generated.ts   names + descriptions; small enough for the
//                               main chunk, which `--help` needs.
//   - topicBodies.generated.ts  the prose; imported dynamically so a normal
//                               extraction never parses it.
//
// The outputs are committed and CI re-runs this script and diffs, the same
// arrangement `scripts/sync-readme-usage.mjs` uses for the README.
//
// Kept build-free so it runs on every Node in the support matrix without
// relying on TypeScript type-stripping.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const topicsDir = resolve(repoRoot, 'docs/cli-topics');
const outDir = resolve(repoRoot, 'src/cli/docs');

const NAME_PATTERN = /^[a-z][a-z0-9-]*$/;
const GENERATED_HEADER = `// Generated by scripts/build-cli-topics.mjs from docs/cli-topics/*.md.
// Do not edit by hand; run \`node scripts/build-cli-topics.mjs\`.
`;

function fail(message) {
  console.error(`build-cli-topics: ${message}`);
  process.exit(1);
}

/**
 * Deliberately not a YAML parser: the frontmatter is two single-line string
 * fields, and accepting more would let a topic carry structure the CLI has
 * no way to render.
 */
function parseTopic(file) {
  const raw = readFileSync(join(topicsDir, file), 'utf8');
  if (!raw.startsWith('---\n')) fail(`${file} does not start with YAML frontmatter`);
  const end = raw.indexOf('\n---\n', 3);
  if (end === -1) fail(`${file} has an unterminated frontmatter block`);

  const fields = {};
  for (const line of raw.slice(4, end + 1).split('\n')) {
    if (line.trim() === '') continue;
    const match = /^([a-z]+):\s*(.*)$/.exec(line);
    if (!match) fail(`${file} has a frontmatter line this script cannot read: ${line}`);
    const [, key, value] = match;
    fields[key] = value.replace(/^["'](.*)["']$/, '$1').trim();
  }

  const expectedName = file.replace(/\.md$/, '');
  if (fields.name !== expectedName) {
    fail(`${file} declares name "${fields.name ?? ''}"; it must match the filename ("${expectedName}")`);
  }
  if (!NAME_PATTERN.test(expectedName)) fail(`${file} is not a usable topic name (lowercase, digits, dashes)`);
  if (!fields.description) fail(`${file} has no description; the index is how an agent picks a topic`);

  const body = raw.slice(end + 5).trim();
  if (!body) fail(`${file} has no body`);
  return { name: expectedName, description: fields.description, body };
}

const files = readdirSync(topicsDir)
  .filter((file) => file.endsWith('.md'))
  .sort();
if (files.length === 0) fail(`no topics found in ${topicsDir}`);

const topics = files.map(parseTopic);

const indexEntries = topics
  .map((topic) => `  { name: ${JSON.stringify(topic.name)}, description: ${JSON.stringify(topic.description)} },`)
  .join('\n');
const indexSource = `${GENERATED_HEADER}
export interface CliTopicSummary {
  name: string;
  description: string;
}

export const CLI_TOPIC_INDEX: readonly CliTopicSummary[] = [
${indexEntries}
];
`;

const bodyEntries = topics.map((topic) => `  ${JSON.stringify(topic.name)}: ${JSON.stringify(topic.body)},`).join('\n');
const bodiesSource = `${GENERATED_HEADER}
export const CLI_TOPIC_BODIES: Record<string, string> = {
${bodyEntries}
};
`;

let changed = false;
for (const [file, source] of [
  ['topicIndex.generated.ts', indexSource],
  ['topicBodies.generated.ts', bodiesSource],
]) {
  const path = join(outDir, file);
  let previous = '';
  try {
    previous = readFileSync(path, 'utf8');
  } catch {
    // first run
  }
  if (previous === source) continue;
  writeFileSync(path, source);
  changed = true;
}

console.log(
  changed
    ? `Generated ${topics.length} CLI topics from docs/cli-topics/.`
    : `CLI topics already up to date (${topics.length}).`,
);
